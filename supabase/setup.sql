create or replace function public.veyli_new_challenge_key(category_uuid uuid,mode_uuid uuid,day date) returns text language plpgsql stable set search_path='' as $$
declare base_key text; candidate text; suffix integer:=2;
begin
  select day::text || '-' || c.slug || '-' || m.slug into base_key from public.veyli_categories c,public.veyli_modes m where c.id=category_uuid and m.id=mode_uuid;
  candidate:=base_key;
  while exists(select 1 from public.veyli_challenges where public_key=candidate) loop
    candidate:=base_key || '-r' || suffix; suffix:=suffix+1;
  end loop;
  return candidate;
end $$;

create or replace function public.veyli_admin_save(entity text, payload jsonb) returns jsonb language plpgsql set search_path = '' as $$
declare object_id uuid; row jsonb; clue jsonb; alias text; category public.veyli_categories; mode public.veyli_modes; desired_status text;
begin
  object_id := coalesce(nullif(payload->>'id','')::uuid,gen_random_uuid());
  if entity = 'item' then
    insert into public.veyli_items(id,slug,category_id,title,release_year,synopsis,source_url,provenance,active)
      values(object_id,payload->>'slug',(payload->>'category_id')::uuid,payload->>'title',(payload->>'release_year')::integer,payload->>'synopsis',payload->>'source_url',coalesce(payload->'provenance','{}'),coalesce((payload->>'active')::boolean,true))
      on conflict(id) do update set slug=excluded.slug,category_id=excluded.category_id,title=excluded.title,release_year=excluded.release_year,synopsis=excluded.synopsis,source_url=excluded.source_url,provenance=excluded.provenance,active=excluded.active;
    delete from public.veyli_aliases where item_id=object_id;
    for alias in select jsonb_array_elements_text(coalesce(payload->'aliases','[]')) loop
      insert into public.veyli_aliases(item_id,title) values(object_id,alias) on conflict(item_id,title) do nothing;
    end loop;
  elsif entity = 'category' then
    insert into public.veyli_categories(id,slug,name,description,accent,icon,active,position)
      values(object_id,payload->>'slug',payload->>'name',payload->>'description',payload->>'accent',payload->>'icon',(payload->>'active')::boolean,(payload->>'position')::integer)
      on conflict(id) do update set slug=excluded.slug,name=excluded.name,description=excluded.description,accent=excluded.accent,icon=excluded.icon,active=excluded.active,position=excluded.position;
  elsif entity = 'mode' then
    insert into public.veyli_modes(id,slug,name,description,icon,active,initial_clues,clues_per_miss,default_attempts,default_scores,position)
      values(object_id,payload->>'slug',payload->>'name',payload->>'description',payload->>'icon',(payload->>'active')::boolean,(payload->>'initial_clues')::integer,(payload->>'clues_per_miss')::integer,(payload->>'default_attempts')::integer,array(select jsonb_array_elements_text(payload->'default_scores')::integer),(payload->>'position')::integer)
      on conflict(id) do update set slug=excluded.slug,name=excluded.name,description=excluded.description,icon=excluded.icon,active=excluded.active,initial_clues=excluded.initial_clues,clues_per_miss=excluded.clues_per_miss,default_attempts=excluded.default_attempts,default_scores=excluded.default_scores,position=excluded.position;
  elsif entity = 'media' then
    insert into public.veyli_media(id,slug,storage_path,kind,quote_text,author,license,license_url,source_url,approved)
      values(object_id,payload->>'slug',nullif(payload->>'storage_path',''),payload->>'kind',nullif(payload->>'quote_text',''),payload->>'author',payload->>'license',payload->>'license_url',payload->>'source_url',(payload->>'approved')::boolean)
      on conflict(id) do update set slug=excluded.slug,storage_path=excluded.storage_path,kind=excluded.kind,quote_text=excluded.quote_text,author=excluded.author,license=excluded.license,license_url=excluded.license_url,source_url=excluded.source_url,approved=excluded.approved;
  elsif entity = 'challenge' then
    if exists(select 1 from public.veyli_sessions where challenge_id=object_id) then raise exception 'Played challenges cannot be edited'; end if;
    select * into category from public.veyli_categories where id=(payload->>'category_id')::uuid;
    select * into mode from public.veyli_modes where id=(payload->>'mode_id')::uuid;
    desired_status:=payload->>'status';
    insert into public.veyli_challenges(id,public_key,category_id,mode_id,answer_id,accepted_answer_ids,release_date,status,difficulty,attempt_limit,scores)
      values(object_id,coalesce((select c.public_key from public.veyli_challenges c where c.id=object_id),public.veyli_new_challenge_key(category.id,mode.id,(payload->>'release_date')::date)),category.id,mode.id,(payload->>'answer_id')::uuid,array(select jsonb_array_elements_text(coalesce(payload->'accepted_answer_ids','[]'))::uuid),(payload->>'release_date')::date,'draft',payload->>'difficulty',(payload->>'attempt_limit')::integer,array(select jsonb_array_elements_text(payload->'scores')::integer))
      on conflict(id) do update set public_key=excluded.public_key,category_id=excluded.category_id,mode_id=excluded.mode_id,answer_id=excluded.answer_id,accepted_answer_ids=excluded.accepted_answer_ids,release_date=excluded.release_date,status='draft',difficulty=excluded.difficulty,attempt_limit=excluded.attempt_limit,scores=excluded.scores;
    delete from public.veyli_clues where challenge_id=object_id;
    for clue in select * from jsonb_array_elements(payload->'clues') loop
      insert into public.veyli_clues(challenge_id,position,kind,text_content,media_id,presentation,blur_amount,crop_percent)
        values(object_id,(clue->>'position')::integer,clue->>'kind',nullif(clue->>'text_content',''),nullif(clue->>'media_id','')::uuid,clue->>'presentation',(clue->>'blur_amount')::integer,(clue->>'crop_percent')::integer);
    end loop;
    if desired_status <> 'draft' and (not exists(select 1 from public.veyli_clues where challenge_id=object_id and position=1)
      or exists(select 1 from public.veyli_clues cl join public.veyli_media m on m.id=cl.media_id where cl.challenge_id=object_id and not m.approved)) then raise exception 'Published challenges require approved clues'; end if;
    update public.veyli_challenges set status=desired_status where id=object_id;
  else raise exception 'Unknown entity'; end if;
  return jsonb_build_object('saved',true,'id',object_id);
end;

-- Only Veyli objects are secured. Existing FitnessJourni objects are untouched.
do $$
declare target record;
begin
  for target in select tablename from pg_tables where schemaname = 'public' and tablename like 'veyli\_%' escape '\' loop
    execute format('alter table public.%I enable row level security',target.tablename);
    execute format('revoke all on public.%I from public, anon, authenticated',target.tablename);
    execute format('grant select, insert, update, delete on public.%I to service_role',target.tablename);
  end loop;
  for target in select p.oid::regprocedure signature from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname like 'veyli\_%' escape '\' loop
    execute format('revoke all on function %s from public, anon, authenticated',target.signature);
    execute format('grant execute on function %s to service_role',target.signature);
  end loop;
end;
$$;

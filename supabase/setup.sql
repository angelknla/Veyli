-- Source-driven Veyli setup. Run in the shared FitnessJourni SQL Editor.
-- Creates app structure and defaults only; no title, image or challenge seeds.
-- Safe to rerun: existing content, clues, guesses and scores are retained.
begin;

create table if not exists public.veyli_categories (
  id uuid primary key default gen_random_uuid(), slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null, description text not null default '', accent text not null default '#ff3045' check (accent ~ '^#[0-9a-fA-F]{6}$'),
  icon text not null default 'film', active boolean not null default true, position integer not null default 0
);
create table if not exists public.veyli_modes (
  id uuid primary key default gen_random_uuid(), slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null, description text not null, icon text not null, active boolean not null default true,
  initial_clues integer not null default 1 check (initial_clues between 1 and 12),
  clues_per_miss integer not null default 1 check (clues_per_miss between 0 and 12),
  default_attempts integer not null default 8 check (default_attempts between 1 and 12),
  default_scores integer[] not null default '{1000,800,650,500,400,300,200,100}'
    check (cardinality(default_scores) = default_attempts and 0 <= all(default_scores) and 100000 >= all(default_scores)),
  position integer not null default 0
);
create table if not exists public.veyli_items (
  id uuid primary key default gen_random_uuid(), slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  category_id uuid not null references public.veyli_categories(id), title text not null check (char_length(title) between 1 and 200),
  release_year integer not null check (release_year between 1800 and 2200), synopsis text not null default '',
  source_url text not null check (source_url ~ '^https://'), provenance jsonb not null default '{}', active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists veyli_items_category on public.veyli_items(category_id);
create table if not exists public.veyli_aliases (
  id uuid primary key default gen_random_uuid(), item_id uuid not null references public.veyli_items(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200), unique(item_id,title)
);
create table if not exists public.veyli_media (
  id uuid primary key default gen_random_uuid(), slug text not null unique, storage_path text unique,
  kind text not null check (kind in ('image','quote')), quote_text text,
  author text not null, license text not null, license_url text not null default '', source_url text not null check (source_url ~ '^https://'),
  approved boolean not null default false, content_type text not null default 'image/jpeg', created_at timestamptz not null default now(),
  check ((kind = 'image' and storage_path is not null) or (kind = 'quote' and quote_text is not null))
);
create table if not exists public.veyli_challenges (
  id uuid primary key default gen_random_uuid(), public_key text not null unique check (public_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  number integer generated by default as identity unique,
  category_id uuid not null references public.veyli_categories(id), mode_id uuid not null references public.veyli_modes(id),
  answer_id uuid not null references public.veyli_items(id), accepted_answer_ids uuid[] not null default '{}',
  release_date date not null, status text not null default 'draft' check (status in ('draft','scheduled','published','archived')),
  difficulty text not null default 'medium' check (difficulty in ('easy','medium','hard')),
  attempt_limit integer not null check (attempt_limit between 1 and 12),
  scores integer[] not null check (cardinality(scores) = attempt_limit and 0 <= all(scores) and 100000 >= all(scores)),
  created_at timestamptz not null default now(), active_revision boolean not null default true
);
alter table public.veyli_challenges add column if not exists active_revision boolean not null default true;
alter table public.veyli_challenges drop constraint if exists veyli_challenges_category_id_mode_id_release_date_key;
create unique index if not exists veyli_current_daily_round on public.veyli_challenges(category_id,mode_id,release_date) where active_revision;
create index if not exists veyli_challenges_release on public.veyli_challenges(release_date,status);
create table if not exists public.veyli_clues (
  id uuid primary key default gen_random_uuid(), challenge_id uuid not null references public.veyli_challenges(id) on delete cascade,
  position integer not null check (position between 1 and 12), kind text not null check (kind in ('image','text','quote')),
  text_content text, media_id uuid references public.veyli_media(id), presentation text not null default 'full' check (presentation in ('full','crop','blur')),
  blur_amount integer not null default 0 check (blur_amount between 0 and 100), crop_percent integer not null default 100 check (crop_percent between 10 and 100),
  unique(challenge_id,position), check ((kind = 'text' and text_content is not null) or (kind in ('image','quote') and media_id is not null))
);
create table if not exists public.veyli_sessions (
  id uuid primary key default gen_random_uuid(), player_key text not null check (player_key ~ '^[a-f0-9]{64}$'),
  challenge_id uuid not null references public.veyli_challenges(id), attempts_used integer not null default 0 check (attempts_used between 0 and 12),
  status text not null default 'in_progress' check (status in ('in_progress','won','lost')), score integer not null default 0 check (score >= 0),
  created_at timestamptz not null default now(), completed_at timestamptz,
  unique(player_key,challenge_id), check ((status = 'in_progress' and completed_at is null and score = 0) or (status <> 'in_progress' and completed_at is not null))
);
create index if not exists veyli_sessions_player on public.veyli_sessions(player_key,completed_at);
create index if not exists veyli_sessions_rankings on public.veyli_sessions(challenge_id,score desc) where status <> 'in_progress';
create table if not exists public.veyli_guesses (
  id uuid primary key default gen_random_uuid(), session_id uuid not null references public.veyli_sessions(id) on delete cascade,
  item_id uuid not null references public.veyli_items(id), attempt integer not null check (attempt between 1 and 12),
  correct boolean not null, created_at timestamptz not null default now(), unique(session_id,item_id), unique(session_id,attempt)
);
create table if not exists public.veyli_rate_windows (
  key text not null, window_start timestamptz not null, count integer not null check (count >= 0), primary key(key,window_start)
);
create table if not exists public.veyli_achievements (
  slug text primary key, name text not null, description text not null, rule jsonb not null
);

create or replace function public.veyli_normalize(value text) returns text language sql immutable set search_path = '' as $$
  select trim(regexp_replace(regexp_replace(translate(lower(value), 'áàâäãåéèêëíìîïóòôöõúùûüñç', 'aaaaaaeeeeiiiiooooouuuunc'), '[^a-z0-9[:space:]]', '', 'g'), '[[:space:]]+', ' ', 'g'));
$$;
create or replace function public.veyli_category_json(category public.veyli_categories) returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object('slug',category.slug,'name',category.name,'description',category.description,'accent',category.accent,'icon',category.icon,'available',category.active);
$$;
create or replace function public.veyli_mode_json(mode public.veyli_modes) returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object('slug',mode.slug,'name',mode.name,'description',mode.description,'icon',mode.icon,'progressive',mode.clues_per_miss > 0);
$$;
create or replace function public.veyli_challenge_json(challenge public.veyli_challenges) returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object('key',challenge.public_key,'number',challenge.number,'releaseDate',challenge.release_date,'difficulty',challenge.difficulty,
    'category',public.veyli_category_json(cat),'mode',public.veyli_mode_json(mode),'attemptLimit',challenge.attempt_limit)
  from public.veyli_categories cat, public.veyli_modes mode where cat.id = challenge.category_id and mode.id = challenge.mode_id;
$$;
create or replace function public.veyli_available(challenge public.veyli_challenges) returns boolean language sql stable set search_path = '' as $$
  select challenge.release_date <= (now() at time zone 'UTC')::date and challenge.status in ('scheduled','published','archived')
    and exists(select 1 from public.veyli_categories cat where cat.id = challenge.category_id and cat.active)
    and exists(select 1 from public.veyli_modes mode where mode.id = challenge.mode_id and mode.active)
    and exists(select 1 from public.veyli_clues clue where clue.challenge_id = challenge.id)
    and not exists(select 1 from public.veyli_clues clue join public.veyli_media media on media.id = clue.media_id where clue.challenge_id = challenge.id and not media.approved);
$$;
create or replace function public.veyli_hub(requested_date date default null) returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'categories',coalesce((select jsonb_agg(public.veyli_category_json(cat) order by cat.position) from public.veyli_categories cat),'[]'::jsonb),
    'modes',coalesce((select jsonb_agg(public.veyli_mode_json(mode) order by mode.position) from public.veyli_modes mode where mode.active),'[]'::jsonb),
    'challenges',coalesce((select jsonb_agg(public.veyli_challenge_json(challenge) order by challenge.release_date desc, cat.position,mode.position)
      from public.veyli_challenges challenge join public.veyli_categories cat on cat.id = challenge.category_id join public.veyli_modes mode on mode.id = challenge.mode_id
      where challenge.active_revision and public.veyli_available(challenge) and challenge.release_date = coalesce(requested_date,(now() at time zone 'UTC')::date)),'[]'::jsonb));
$$;
create or replace function public.veyli_search(query text, category_slug text) returns jsonb language sql stable set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('slug',item.slug,'title',item.title,'year',item.release_year,'category',item.category_slug) order by item.title),'[]'::jsonb)
  from (select i.slug,i.title,i.release_year,c.slug category_slug from public.veyli_items i join public.veyli_categories c on c.id = i.category_id
    where i.active and c.active and c.slug = category_slug and char_length(public.veyli_normalize(query)) between 1 and 100
      and (public.veyli_normalize(i.title) like '%' || public.veyli_normalize(query) || '%'
        or exists(select 1 from public.veyli_aliases a where a.item_id = i.id and public.veyli_normalize(a.title) like '%' || public.veyli_normalize(query) || '%'))
    order by i.title limit 12) item;
$$;
create or replace function public.veyli_take_rate(rate_key text, maximum integer, window_seconds integer) returns boolean language plpgsql set search_path = '' as $$
declare start_time timestamptz; new_count integer;
begin
  if char_length(rate_key) > 180 or maximum not between 1 and 500 or window_seconds not between 1 and 3600 then return false; end if;
  start_time := to_timestamp(floor(extract(epoch from now()) / window_seconds) * window_seconds);
  insert into public.veyli_rate_windows(key,window_start,count) values (rate_key,start_time,1)
    on conflict(key,window_start) do update set count = public.veyli_rate_windows.count + 1 where public.veyli_rate_windows.count < maximum
    returning count into new_count;
  delete from public.veyli_rate_windows where window_start < now() - interval '2 hours';
  return new_count is not null;
end;
$$;
create or replace function public.veyli_session_json(session public.veyli_sessions) returns jsonb language plpgsql stable set search_path = '' as $$
declare challenge public.veyli_challenges; mode public.veyli_modes; visible integer; answer jsonb;
begin
  select * into challenge from public.veyli_challenges where id = session.challenge_id;
  select * into mode from public.veyli_modes where id = challenge.mode_id;
  visible := case when session.status <> 'in_progress' then 12 else mode.initial_clues + session.attempts_used * mode.clues_per_miss end;
  if session.status <> 'in_progress' then
    select jsonb_build_object('slug',i.slug,'title',i.title,'year',i.release_year,'synopsis',i.synopsis,'sourceUrl',i.source_url,
      'credits',coalesce((select jsonb_agg(distinct jsonb_build_object('author',m.author,'license',m.license,'licenseUrl',m.license_url,'sourceUrl',m.source_url))
        from public.veyli_clues cl join public.veyli_media m on m.id = cl.media_id where cl.challenge_id = challenge.id),'[]'::jsonb))
    into answer from public.veyli_items i where i.id = challenge.answer_id;
  end if;
  return jsonb_build_object('challenge',public.veyli_challenge_json(challenge),'attemptsUsed',session.attempts_used,'status',session.status,'score',session.score,'completedAt',session.completed_at,'answer',answer,
    'clues',coalesce((select jsonb_agg(jsonb_build_object('position',cl.position,'kind',cl.kind,
      'text',case when cl.kind = 'quote' then m.quote_text else cl.text_content end,'presentation',cl.presentation,
      'imageUrl',case when cl.kind = 'image' then '/api/challenges/' || challenge.public_key || '/media/' || cl.position else null end) order by cl.position)
      from public.veyli_clues cl left join public.veyli_media m on m.id = cl.media_id where cl.challenge_id = challenge.id and cl.position <= visible),'[]'::jsonb),
    'guesses',coalesce((select jsonb_agg(jsonb_build_object('slug',i.slug,'title',i.title,'year',i.release_year,'correct',g.correct) order by g.attempt)
      from public.veyli_guesses g join public.veyli_items i on i.id = g.item_id where g.session_id = session.id),'[]'::jsonb));
end;
$$;
create or replace function public.veyli_play(player_digest text, challenge_key text, selected_slug text default null) returns jsonb language plpgsql set search_path = '' as $$
declare challenge public.veyli_challenges; session public.veyli_sessions; item public.veyli_items; correct boolean; next_attempt integer;
begin
  if player_digest !~ '^[a-f0-9]{64}$' then return jsonb_build_object('error','invalid_player'); end if;
  select * into challenge from public.veyli_challenges where public_key = challenge_key;
  if not found or not public.veyli_available(challenge) then return jsonb_build_object('error','challenge_unavailable'); end if;
  if selected_slug is not null then
    select * into item from public.veyli_items where slug = selected_slug and active and category_id = challenge.category_id;
    if not found then return jsonb_build_object('error','invalid_answer'); end if;
  end if;
  insert into public.veyli_sessions(player_key,challenge_id) values(player_digest,challenge.id) on conflict(player_key,challenge_id) do nothing;
  select * into session from public.veyli_sessions where player_key = player_digest and challenge_id = challenge.id for update;
  if selected_slug is null then return public.veyli_session_json(session); end if;
  if session.status <> 'in_progress' then return jsonb_build_object('error','game_complete','state',public.veyli_session_json(session)); end if;
  if exists(select 1 from public.veyli_guesses where session_id = session.id and item_id = item.id) then return jsonb_build_object('error','duplicate_answer'); end if;
  next_attempt := session.attempts_used + 1;
  if next_attempt > challenge.attempt_limit then return jsonb_build_object('error','game_complete'); end if;
  correct := item.id = challenge.answer_id or item.id = any(challenge.accepted_answer_ids);
  insert into public.veyli_guesses(session_id,item_id,attempt,correct) values(session.id,item.id,next_attempt,correct);
  update public.veyli_sessions set attempts_used = next_attempt,
    status = case when correct then 'won' when next_attempt = challenge.attempt_limit then 'lost' else 'in_progress' end,
    score = case when correct then challenge.scores[next_attempt] else 0 end,
    completed_at = case when correct or next_attempt = challenge.attempt_limit then now() else null end
    where id = session.id returning * into session;
  return public.veyli_session_json(session);
end;
$$;
create or replace function public.veyli_media_access(player_digest text, challenge_key text, clue_position integer) returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object('storagePath',media.storage_path,'presentation',clue.presentation,'blur',case when session.status <> 'in_progress' then 0 else clue.blur_amount end,
    'cropPercent',case when session.status <> 'in_progress' then 100 else clue.crop_percent end,'contentType',media.content_type)
  from public.veyli_sessions session join public.veyli_challenges challenge on challenge.id = session.challenge_id
    join public.veyli_modes mode on mode.id = challenge.mode_id join public.veyli_clues clue on clue.challenge_id = challenge.id
    join public.veyli_media media on media.id = clue.media_id
  where session.player_key = player_digest and challenge.public_key = challenge_key and public.veyli_available(challenge)
    and clue.position = clue_position and clue.kind = 'image' and media.approved
    and (session.status <> 'in_progress' or clue.position <= mode.initial_clues + session.attempts_used * mode.clues_per_miss);
$$;
create or replace function public.veyli_completions(player_digest text) returns jsonb language sql stable set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object('key',challenge.public_key,'category',cat.slug,'mode',mode.slug,'releaseDate',challenge.release_date,
    'completedAt',session.completed_at,'status',session.status,'attemptsUsed',session.attempts_used,'score',session.score) order by session.completed_at),'[]'::jsonb)
  from public.veyli_sessions session join public.veyli_challenges challenge on challenge.id = session.challenge_id
  join public.veyli_categories cat on cat.id = challenge.category_id join public.veyli_modes mode on mode.id = challenge.mode_id
  where session.player_key = player_digest and session.status <> 'in_progress';
$$;
create or replace function public.veyli_leaderboard(requested_date date) returns jsonb language sql stable set search_path='' as $$
 select coalesce(jsonb_agg(to_jsonb(entry)),'[]'::jsonb) from (
  select 'Player ' || upper(substr(md5(rounds.player_key || requested_date::text),1,6)) alias,
    sum(rounds.score)::integer score,count(*)::integer games,count(*) filter(where rounds.won)::integer wins
  from (select s.player_key,c.category_id,c.mode_id,max(s.score) score,bool_or(s.status='won') won
    from public.veyli_sessions s join public.veyli_challenges c on c.id=s.challenge_id
    where c.release_date=requested_date and s.status<>'in_progress' and public.veyli_available(c)
    group by s.player_key,c.category_id,c.mode_id) rounds
  group by rounds.player_key order by score desc,wins desc,alias limit 50
 ) entry;
$$;

create or replace function public.veyli_validate_challenge() returns trigger language plpgsql set search_path = '' as $$
begin
  if not exists(select 1 from public.veyli_items where id = new.answer_id and category_id = new.category_id) then raise exception 'Answer category does not match'; end if;
  if exists(select 1 from unnest(new.accepted_answer_ids) accepted where not exists(select 1 from public.veyli_items where id = accepted and category_id = new.category_id)) then raise exception 'Accepted answer category does not match'; end if;
  if tg_op = 'UPDATE' and exists(select 1 from public.veyli_sessions where challenge_id = old.id) then
    if (new.public_key,new.category_id,new.mode_id,new.answer_id,new.accepted_answer_ids,new.release_date,new.attempt_limit,new.scores)
      is distinct from (old.public_key,old.category_id,old.mode_id,old.answer_id,old.accepted_answer_ids,old.release_date,old.attempt_limit,old.scores) or new.status = 'draft' then
      raise exception 'Played challenge rules are immutable';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists veyli_validate_challenge on public.veyli_challenges;
create trigger veyli_validate_challenge before insert or update on public.veyli_challenges for each row execute function public.veyli_validate_challenge();
create or replace function public.veyli_freeze_mode() returns trigger language plpgsql set search_path = '' as $$
begin
  if (new.initial_clues,new.clues_per_miss) is distinct from (old.initial_clues,old.clues_per_miss)
    and exists(select 1 from public.veyli_sessions s join public.veyli_challenges c on c.id = s.challenge_id where c.mode_id = old.id) then raise exception 'Played mode reveal rules are immutable'; end if;
  return new;
end;
$$;
drop trigger if exists veyli_freeze_mode on public.veyli_modes;
create trigger veyli_freeze_mode before update on public.veyli_modes for each row execute function public.veyli_freeze_mode();

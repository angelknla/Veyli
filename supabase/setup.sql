$$;
create or replace function public.veyli_hub_filtered(requested_date date default null,start_year integer default 1800,end_year integer default 2200) returns jsonb language sql stable set search_path='' as $$
  select jsonb_set(public.veyli_hub(requested_date),'{challenges}',coalesce((
    select jsonb_agg(entry) from jsonb_array_elements(public.veyli_hub(requested_date)->'challenges') entry
